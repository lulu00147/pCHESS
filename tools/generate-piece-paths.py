#!/usr/bin/env python3

from __future__ import annotations

import re
from pathlib import Path

from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
CHESS_FONT = ROOT / "tools/cache/fonts/dejavu/dejavu-sans-ttf-2.37/ttf/DejaVuSans.ttf"
XIANGQI_FONT = Path(r"C:\Windows\Fonts\NotoSerifSC-VF.ttf")
OUT = ROOT / "src/board/appearance/glyphs.ts"

CHESS = {
    "K": 0x265A,
    "Q": 0x265B,
    "R": 0x265C,
    "B": 0x265D,
    "N": 0x265E,
    "P": 0x265F,
}

XIANGQI = {
    "wK": "帥",
    "bK": "將",
    "wA": "仕",
    "bA": "士",
    "wB": "相",
    "bB": "象",
    "wN": "馬",
    "bN": "馬",
    "wR": "車",
    "bR": "車",
    "wC": "炮",
    "bC": "炮",
    "wP": "兵",
    "bP": "卒",
}


def normalize(path_data: str) -> str:
    return re.sub(r"-?\d+\.\d+", lambda match: f"{float(match.group()):.2f}", path_data)


def glyph_path(font: TTFont, codepoint: int, target: float) -> str:
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    name = cmap[codepoint]
    glyph = glyph_set[name]

    bounds_pen = BoundsPen(glyph_set)
    glyph.draw(bounds_pen)
    if bounds_pen.bounds is None:
        raise ValueError(f"glyph {name} has no outline")

    x0, y0, x1, y1 = bounds_pen.bounds
    width = max(x1 - x0, 1)
    height = max(y1 - y0, 1)
    scale = min(target / width, target / height)
    center_x = (x0 + x1) / 2
    center_y = (y0 + y1) / 2

    transform = Transform(scale, 0, 0, -scale, 50 - center_x * scale, 50 + center_y * scale)
    svg_pen = SVGPathPen(glyph_set)
    glyph.draw(TransformPen(svg_pen, transform))
    return normalize(svg_pen.getCommands())


def main() -> None:
    chess_font = TTFont(str(CHESS_FONT), fontNumber=0)
    xiangqi_font = TTFont(str(XIANGQI_FONT), fontNumber=0)

    chess_paths = {key: glyph_path(chess_font, code, 78) for key, code in CHESS.items()}
    xiangqi_paths = {
        key: glyph_path(xiangqi_font, ord(char), 54) for key, char in XIANGQI.items()
    }

    lines = [
        "/* Generated by tools/generate-piece-paths.py; do not edit by hand. */",
        "",
        "export const CHESS_GLYPHS = {",
    ]
    for key, value in chess_paths.items():
        lines.append(f"  {key}: '{value}',")
    lines.extend(["};", "", "export const XIANGQI_GLYPHS = {"])
    for key, value in xiangqi_paths.items():
        lines.append(f"  {key}: '{value}',")
    lines.extend(["};", ""])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
